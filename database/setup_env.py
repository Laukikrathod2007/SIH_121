"""
Helper script to create and configure .env file
"""

import os
import getpass

print("""
╔══════════════════════════════════════════════════════════════════╗
║                                                                  ║
║                  NWIS Database Configuration                     ║
║                   .env File Setup Helper                         ║
║                                                                  ║
╚══════════════════════════════════════════════════════════════════╝
""")

print("This script will help you create the .env configuration file.\n")

# Check if .env already exists
env_file = ".env"
if os.path.exists(env_file):
    print(f"⚠️  Warning: {env_file} already exists!")
    response = input("Do you want to overwrite it? (y/n): ").strip().lower()
    if response != 'y':
        print("\nExiting without changes.")
        exit(0)
    print()

# Get configuration values
print("Please provide your PostgreSQL configuration:")
print("(Press Enter to use default values shown in brackets)\n")

db_host = input("Database Host [localhost]: ").strip() or "localhost"
db_port = input("Database Port [5432]: ").strip() or "5432"
db_name = input("Database Name [nwis_db]: ").strip() or "nwis_db"
db_user = input("Database User [postgres]: ").strip() or "postgres"

# Get password securely (hidden input)
print("\nDatabase Password (input will be hidden):")
db_password = getpass.getpass("Password: ")

if not db_password:
    print("\n❌ Error: Password cannot be empty!")
    exit(1)

# Confirm password
db_password_confirm = getpass.getpass("Confirm Password: ")

if db_password != db_password_confirm:
    print("\n❌ Error: Passwords do not match!")
    exit(1)

# Create .env file
env_content = f"""# NWIS Database Configuration
# Auto-generated by setup_env.py
# DO NOT commit this file to version control!

DB_HOST={db_host}
DB_PORT={db_port}
DB_NAME={db_name}
DB_USER={db_user}
DB_PASSWORD={db_password}
"""

try:
    with open(env_file, 'w') as f:
        f.write(env_content)
    
    print("\n" + "=" * 70)
    print("✅ SUCCESS! .env file created successfully")
    print("=" * 70)
    
    print("\n📋 Configuration Summary:")
    print(f"   Host:     {db_host}")
    print(f"   Port:     {db_port}")
    print(f"   Database: {db_name}")
    print(f"   User:     {db_user}")
    print(f"   Password: {'*' * len(db_password)} (hidden)")
    
    print("\n🔒 Security Notes:")
    print("   • .env file is in .gitignore (won't be committed)")
    print("   • Keep this file secure and never share it")
    print("   • Different environments should have different .env files")
    
    print("\n🚀 Next Steps:")
    print("   1. Test connection: python config/db_config.py")
    print("   2. Initialize database: python init_database.py")
    
except Exception as e:
    print(f"\n❌ Error creating .env file: {e}")
    exit(1)
