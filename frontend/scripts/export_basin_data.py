"""Exports the demo basin (12 Upper Assam wells) from the NWIS backend into
frontend/src/story/basinData.json for the 3D story page: surface position,
total depth, trajectory stations, formation tops and drilling events.

Run from the Backend folder (so the `app` package resolves):
    cd Backend
    python ../frontend/scripts/export_basin_data.py
"""
from __future__ import annotations

import json
import math
import sys
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")
sys.path.insert(0, str(Path.cwd()))

from loguru import logger  # noqa: E402

logger.remove()
from fastapi.testclient import TestClient  # noqa: E402
from app.main import app  # noqa: E402

ACTIVE = "WELL-NHK-002"
OUT = Path(__file__).resolve().parent.parent / "src" / "story" / "basinData.json"
DDR_DIR = Path.cwd().parent / "real_data" / "evidence_pdfs"


def ddr_depths(well_id: str) -> list[float]:
    """Depths of the daily drilling reports on file for a well
    (real_data/evidence_pdfs/DDR_<well>_<depth>m.pdf)."""
    out = []
    for p in DDR_DIR.glob(f"DDR_{well_id}_*m.pdf"):
        try:
            out.append(float(p.stem.rsplit("_", 1)[1].rstrip("m")))
        except ValueError:
            pass
    return sorted(out)


def km_offsets(lat0: float, lon0: float, lat: float, lon: float) -> tuple[float, float]:
    east = (lon - lon0) * 111.32 * math.cos(math.radians(lat0))
    north = (lat - lat0) * 110.57
    return round(east, 3), round(north, 3)


with TestClient(app) as c:
    wells = [w for w in c.get("/api/v2/map/wells").json()["wells"] if w["well_id"].startswith("WELL-")]
    active = next(w for w in wells if w["well_id"] == ACTIVE)
    out = {
        "_source": "Generated by frontend/scripts/export_basin_data.py from the NWIS backend (demo testbed).",
        "active": ACTIVE,
        "wells": [],
    }
    for w in sorted(wells, key=lambda w: w["well_id"]):
        wid = w["well_id"]
        east, north = km_offsets(active["lat"], active["lon"], w["lat"], w["lon"])
        traj = c.get(f"/api/v2/trajectory/{wid}")
        stations = traj.json().get("stations", []) if traj.status_code == 200 else []
        # Keep roughly one station per 100 m of MD.
        keep, last = [], -1e9
        for s in stations:
            if s["md_m"] - last >= 100 or s is stations[-1]:
                keep.append([round(s["md_m"], 1), round(s["tvd_m"], 1), round(s["ns_m"], 1), round(s["ew_m"], 1)])
                last = s["md_m"]
        tops = c.get(f"/api/v2/formations/{wid}").json().get("formation_tops", [])
        events = c.get(f"/api/v2/events/{wid}").json().get("events", [])
        out["wells"].append({
            "id": wid.replace("WELL-", ""),
            "field": w.get("field"),
            "east_km": east,
            "north_km": north,
            "td_md": w.get("total_depth_md_m"),
            "type": w.get("well_type"),
            "stations": keep,
            "tops": [
                {"name": t["formation_name"], "md": round(t["top_md_m"], 1), "tvd": round(t.get("top_tvd_m") or t["top_md_m"], 1)}
                for t in sorted(tops, key=lambda t: t["top_md_m"])
            ],
            "events": [
                {"id": e.get("event_id"), "type": e.get("event_type"), "md": round(e.get("depth_start_md_m") or 0, 1),
                 "formation": e.get("formation"), "severity": e.get("severity")}
                for e in events
            ],
            "ddrs": ddr_depths(wid),
        })

OUT.write_text(json.dumps(out, indent=1), encoding="utf-8")
print(f"wrote {OUT} ({len(out['wells'])} wells, {sum(len(w['events']) for w in out['wells'])} events)")
